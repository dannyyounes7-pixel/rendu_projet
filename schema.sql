CREATE TABLE IF NOT EXISTS fichiers_traites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_fichier TEXT NOT NULL,
    empreinte_sha256 CHAR(64) NOT NULL UNIQUE,
    date_traitement TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sommes_par_iban_origine (
    fichier_id BIGINT NOT NULL REFERENCES fichiers_traites(id) ON DELETE CASCADE,
    iban_origine TEXT NOT NULL,
    montant_total NUMERIC(18, 2) NOT NULL,
    PRIMARY KEY (fichier_id, iban_origine)
);

CREATE TABLE IF NOT EXISTS sommes_par_banque (
    fichier_id BIGINT NOT NULL REFERENCES fichiers_traites(id) ON DELETE CASCADE,
    banque_source TEXT NOT NULL,
    montant_total NUMERIC(18, 2) NOT NULL,
    PRIMARY KEY (fichier_id, banque_source)
);

CREATE TABLE IF NOT EXISTS sommes_recues_par_iban (
    fichier_id BIGINT NOT NULL REFERENCES fichiers_traites(id) ON DELETE CASCADE,
    iban_destinataire TEXT NOT NULL,
    montant_total NUMERIC(18, 2) NOT NULL,
    PRIMARY KEY (fichier_id, iban_destinataire)
);

CREATE TABLE IF NOT EXISTS transactions_flaggees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fichier_id BIGINT NOT NULL REFERENCES fichiers_traites(id) ON DELETE CASCADE,
    datetime_transaction TIMESTAMP NOT NULL,
    iban_origine TEXT NOT NULL,
    pays_source TEXT NOT NULL,
    banque_source TEXT NOT NULL,
    iban_destinataire TEXT NOT NULL,
    pays_destinataire TEXT NOT NULL,
    montant NUMERIC(18, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_transactions_flaggees_fichier
    ON transactions_flaggees (fichier_id);